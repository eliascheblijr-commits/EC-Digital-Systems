// ============ CANVAS SCROLL SCRUBBING (HOME PAGE) ============
const productCanvas = document.getElementById("home-canvas");

if (productCanvas) {
  const context = productCanvas.getContext("2d");
  const frameCount = 240; // Exact number of frames generated by FFmpeg
  let currentFrameIndex = -1;

  // Set physical rendering resolution corresponding to the FFmpeg export
  productCanvas.width = 1280;
  productCanvas.height = 960;

  // Path resolver
  const currentFrame = index => (
    `/assets/images/home-bg/frame_${index.toString().padStart(3, '0')}.webp`
  );

  // Preload all frames into memory
  const images = [];
  for (let i = 1; i <= frameCount; i++) {
    const img = new Image();
    img.src = currentFrame(i);
    images.push(img);
  }

  // Paint the absolute first frame immediately on load
  const initialImg = new Image();
  initialImg.src = currentFrame(1);
  initialImg.onload = () => {
    context.drawImage(initialImg, 0, 0, productCanvas.width, productCanvas.height);
  };

  // Map scroll depth to the frame array
  const renderCanvas = () => {
    const html = document.documentElement;
    const body = document.body;
    
    // Calculate total scrollable area
    const maxScrollTop = Math.max(html.scrollHeight, body.scrollHeight) - window.innerHeight;
    const scrollTop = window.scrollY || html.scrollTop;
    
    // Prevent division by zero if page content isn't long enough to scroll
    const scrollFraction = maxScrollTop > 0 ? scrollTop / maxScrollTop : 0;
    
    // Lock the index to prevent array out-of-bounds errors
    const frameIndex = Math.min(
      frameCount - 1,
      Math.floor(scrollFraction * frameCount)
    );
    
    // Only redraw if the user actually scrolled enough to advance a frame
    if (frameIndex !== currentFrameIndex && images[frameIndex] && images[frameIndex].complete) {
      context.drawImage(images[frameIndex], 0, 0, productCanvas.width, productCanvas.height);
      currentFrameIndex = frameIndex;
    }
  };

  // Utilize requestAnimationFrame for ultra-smooth 60fps binding
  let ticking = false;
  window.addEventListener("scroll", () => {
    if (!ticking) {
      window.requestAnimationFrame(() => {
        renderCanvas();
        ticking = false;
      });
      ticking = true;
    }
  }, { passive: true });
}